function Block({ block }) {
  const [type, content] = block;
  switch (type) {
    case "h":
      return <h3 className="font-bold text-slate-800 pt-2">{content}</h3>;
    case "ul":
      return (
        <ul className="list-disc pl-6 space-y-1.5">
          {content.map((item) => <li key={item}>{item}</li>)}
        </ul>
      );
    case "ol":
      return (
        <ol className="list-decimal pl-6 space-y-1.5">
          {content.map((item) => <li key={item}>{item}</li>)}
        </ol>
      );
    case "email":
      return <p>{content} <EmailLink /></p>;
    case "contact":
      return (
        <p>
          <span className="font-bold text-slate-800">Team Kizuna</span><br />
          Developer of LIG+AS — Learning in Gamified + Applied Simulation<br />
          Email: <EmailLink />
        </p>
      );
    default:
      return <p>{content}</p>;
  }
}

